import {chooseEnvironment,prepareSse} from './helpers';
import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
const root=path.resolve('..');
test('浏览器：配对、建环境、切换、发送、SSE、记录与会话恢复',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 const pair=execFileSync(path.join(root,'.venv/Scripts/python.exe'),['-m','api_post','pair','--port','18767','--workspace',process.env.API_LAB_E2E_WORKSPACE!],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim();
 await page.getByLabel('本机配对码').fill(pair);
 await page.getByRole('button',{name:'连接工作区'}).click();
 await expect(page.getByRole('heading',{name:'请求工作台'})).toBeVisible();
 const label='本机演示 '+Date.now();
 await page.getByRole('button',{name:'＋ 新建环境'}).click();
 await page.getByLabel('环境名称').fill(label);
 await page.getByLabel('基础地址').fill('http://127.0.0.1:18768');
 await page.getByRole('button',{name:'保存环境',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByLabel('请求名称').fill('浏览器 JSON 验证');
 await page.getByLabel('请求正文').fill('{"message":"界面与请求记录已连通"}');
 await page.getByRole('button',{name:'发送请求'}).click();
 await expect(page.locator('.status-pill').last()).toContainText('已完成');
 await expect(page.locator('.response-content')).toContainText('界面与请求记录已连通');
 await expect(page.locator('.check-label')).toContainText('检查通过');
 await page.getByRole('button',{name:'请求快照',exact:true}).click();
 await expect(page.locator('.response-content')).toContainText('user-agent');
 await expect(page.locator('.response-content')).toContainText('发送前构建的最终请求头');
 await page.getByRole('button',{name:'响应头',exact:true}).click();
 await expect(page.locator('.response-content')).toContainText('x-demo-server');
 // Opening history must show the recorded request, not the current draft.
 await page.getByLabel('请求正文',{exact:true}).fill('{"message":"unsent draft"}');
 const before=await (await page.request.get('/api/runs?limit=200')).json();
 const saved=await (await page.request.get('/api/runs/'+before.items.find((r:any)=>r.name==='浏览器 JSON 验证').id)).json();
 await page.locator('.recent').filter({hasText:'浏览器 JSON 验证'}).first().click();
 const snapshot=page.getByRole('region',{name:'历史请求快照'});
 await expect(snapshot.getByLabel('快照请求正文')).toHaveValue(saved.request.body);
 await expect(snapshot.getByLabel('快照请求正文')).toHaveAttribute('readonly','');
 await expect(snapshot.getByLabel('快照请求地址')).toHaveValue('http://127.0.0.1:18768/echo');
 for(const width of [1440,900]){
  await page.setViewportSize({width,height:1000});
  const method=await snapshot.getByLabel('快照请求方法').boundingBox(),address=await snapshot.getByLabel('快照请求地址').boundingBox();
  expect(method!.width).toBeGreaterThanOrEqual(89);expect(method!.x+method!.width).toBeLessThanOrEqual(address!.x+1);expect(address!.width).toBeGreaterThan(100);
 }
 await page.setViewportSize({width:1440,height:1000});

 await expect(page.locator('.request-toolbar')).toContainText(label);
 await snapshot.getByRole('button',{name:'请求头',exact:true}).click();
 await expect(snapshot.getByLabel('快照请求头')).toContainText('user-agent');
 expect((await (await page.request.get('/api/runs?limit=200')).json()).total).toBe(before.total);
 await snapshot.getByRole('button',{name:'编辑并复测'}).click();
 await expect(page.getByLabel('请求正文',{exact:true})).toHaveValue(saved.request.body);
 await page.getByLabel('请求正文',{exact:true}).fill('{"message":"new replay"}');
 await page.getByRole('button',{name:'发送请求'}).click();
 await expect(page.locator('.status-pill').last()).toContainText('已完成');
 await expect(page.locator('.response-content')).toContainText('new replay');
 expect((await (await page.request.get('/api/runs?limit=200')).json()).total).toBe(before.total+1);
 const original=await (await page.request.get('/api/runs/'+before.items.find((r:any)=>r.name==='浏览器 JSON 验证').id)).json();
 expect(original.request.body).toBe(saved.request.body);
 await page.getByRole('button',{name:'＋ 新建环境'}).click();
 await page.getByLabel('环境名称').fill(label+' · 国内测试');
 await page.getByLabel('基础地址').fill('http://127.0.0.1:18768');
 await page.getByLabel('环境区域',{exact:true}).selectOption('domestic');
 await page.getByLabel('环境阶段').selectOption('test');
 await page.getByRole('button',{name:'保存环境',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await chooseEnvironment(page,label);
 await prepareSse(page);
 await page.getByRole('button',{name:'发送请求'}).click();
 await expect(page.locator('.status-pill').last()).toContainText('已完成');
 await expect(page.locator('.response-content')).toContainText('流式响应');
 await expect(page.locator('.check-label')).toContainText('检查通过');
 await page.getByRole('button',{name:'流事件',exact:false}).click();
 await expect(page.locator('.response-content')).toContainText('[DONE]');
 await page.getByRole('button',{name:'请求记录',exact:false}).first().click();
 await expect(page.getByRole('heading',{name:'请求记录'})).toBeVisible();
 await expect(page.locator('tbody')).toContainText('浏览器 JSON 验证');
 await expect(page.locator('tbody')).toContainText('流式连通性验证');
 await page.getByRole('button',{name:'环境管理',exact:false}).first().click();
 await expect(page.getByRole('heading',{name:'环境管理'})).toBeVisible();
 await expect(page.getByRole('heading',{name:label,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'请求工作台',exact:false}).first().click();
 await page.getByRole('button',{name:'正文',exact:true}).last().click();
 await page.screenshot({path:path.join(root,'workspace/qa/workbench.png'),fullPage:true});
 const other=await context.newPage();await other.goto('/');
 await expect(other.getByRole('heading',{name:'请求工作台'})).toBeVisible();
 await other.getByRole('combobox',{name:'执行环境',exact:true}).click();
 await other.getByRole('textbox',{name:'搜索执行环境',exact:true}).fill(label);
 await expect(other.getByRole('option').filter({hasText:label})).toHaveCount(2);
 await other.close();
 expect(errors).toEqual([]);
});
