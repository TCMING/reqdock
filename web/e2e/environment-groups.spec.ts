import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {chooseEnvironment} from './helpers';
const root=path.resolve('..');
test('同环境一张卡片，统一编辑后所有服务连接使用最新值',async({page})=>{
 await page.goto('/');const code=execFileSync(path.join(root,'.venv/Scripts/python.exe'),['-m','api_post','pair','--port','18767','--workspace',process.env.API_LAB_E2E_WORKSPACE!],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim();await page.getByLabel('本机配对码').fill(code);await page.getByRole('button',{name:'连接工作区'}).click();
 const label='分组界面验证 '+Date.now(),source='fixture-group-'+Date.now();
 const session=await (await page.request.get('/api/auth/session')).json();
 const document={openapi:'3.0.3',info:{title:'Fixture',version:'1'},servers:[{description:label,url:'',variables:{a:{default:'http://127.0.0.1:18768/a'},b:{default:'http://127.0.0.1:18768/b'},label:{default:'old'}}}],paths:{'/echo':{post:{summary:'本机分组验证'}}}};
 const response=await page.request.post('/api/import/openapi',{headers:{Origin:'http://127.0.0.1:18767','X-CSRF-Token':session.csrf},data:{source_id:source,document}});
 expect(response.ok()).toBeTruthy();
 await page.getByRole('button',{name:'环境管理',exact:false}).first().click();
 await page.getByLabel('搜索环境').fill('本地环境');
 await expect(page.locator('.env-card').filter({has:page.getByRole('heading',{name:'本地环境',exact:true})})).toHaveCount(1);
 const imported=page.locator('.env-card').filter({has:page.getByRole('heading',{name:'本地环境',exact:true})});
 await expect(imported).toContainText('ibrain-common');await expect(imported).toContainText('aibots-common');
 await page.getByLabel('搜索环境').fill(label);
 const card=page.locator('.env-card').filter({has:page.getByRole('heading',{name:label,exact:true})});
 await expect(card).toHaveCount(1);await expect(card).toContainText('2 个服务地址');
 await card.getByRole('button',{name:'编辑环境',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'编辑环境组'}),rows=dialog.locator('.variable-row');
 await rows.nth(0).getByLabel('变量值',{exact:true}).fill('http://127.0.0.1:18768/changed-a');
 await rows.nth(2).getByLabel('变量值',{exact:true}).fill('shared latest');
 await dialog.getByRole('button',{name:'保存环境',exact:true}).click();
 await expect(dialog).toHaveCount(0);await expect(card).toContainText('shared latest');
 const groups=await (await page.request.get('/api/environment-groups')).json();const group=groups.find((g:any)=>g.name===label);
 expect(group.members).toHaveLength(2);expect(group.members.every((m:any)=>m.environment.variables.label==='shared latest')).toBeTruthy();
 await card.getByRole('button',{name:'使用此环境'}).click();await chooseEnvironment(page,label);
 await page.getByLabel('请求路径',{exact:true}).fill('{{b}}/echo');
 await expect(page.getByLabel('最终地址',{exact:true})).toHaveText('http://127.0.0.1:18768/b');
 await page.getByLabel('请求正文').fill('{"label":"{{label}}"}');await page.getByLabel('请求路径').fill('{{b}}/echo');await page.getByRole('button',{name:'发送请求'}).click();
 await expect(page.locator('.status-pill').last()).toContainText('已完成');await expect(page.locator('.response-content')).toContainText('shared latest');
 await page.getByRole('button',{name:'环境管理',exact:false}).first().click();await page.getByLabel('搜索环境').fill('本地环境');
 await page.screenshot({path:path.join(root,'workspace/qa/environment-groups.png'),fullPage:true});
});
