import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
test('迁入的用例库可搜索载入，浏览器刷新无需重新配对',async({page})=>{
 const root=path.resolve('..');
 await page.goto('/');
 const pair=execFileSync(path.join(root,'.venv/Scripts/python.exe'),['-m','api_post','pair','--port','18767','--workspace',process.env.API_LAB_E2E_WORKSPACE!],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim();
 await page.getByLabel('本机配对码').fill(pair);
 await page.getByRole('button',{name:'连接工作区'}).click();
 await page.getByRole('button',{name:'用例库',exact:false}).click();
 await expect(page.getByRole('heading',{name:'用例库',exact:true})).toBeVisible();
 // Local cases can now be added alongside the 146 imported operations.
 await expect.poll(async()=>Number((await page.locator('.case-library .pagination').innerText()).match(/共 (\d+) 个接口/)?.[1]||0)).toBeGreaterThanOrEqual(146);
 const group=page.getByRole('combobox',{name:'用例业务',exact:true});
 await group.click();
 await page.getByRole('textbox',{name:'搜索用例业务',exact:true}).fill('生图片/banana');
 const choice=page.getByRole('option',{name:'Prompt工程 / 生图片/banana',exact:true});
 await expect(choice).toBeVisible();
 await page.screenshot({path:path.join(root,'workspace/qa/group-picker-open.png'),fullPage:true});
 await page.setViewportSize({width:900,height:800});
 const popup=await page.locator('.select-popover').boundingBox();
 expect(popup).not.toBeNull();
 expect(popup!.x).toBeGreaterThanOrEqual(0);expect(popup!.x+popup!.width).toBeLessThanOrEqual(900);
 await page.setViewportSize({width:1440,height:1000});
 await expect(page.locator('.select-options')).toHaveCSS('overflow-y','auto');
 await choice.click();
 await expect(group).toContainText('生图片/banana');
 await expect.poll(()=>page.locator('tbody tr').count()).toBeGreaterThan(0);
 await group.click();
 await page.getByRole('textbox',{name:'搜索用例业务',exact:true}).fill('全部业务');
 await page.getByRole('textbox',{name:'搜索用例业务',exact:true}).press('Enter');
 await expect(group).toContainText('全部业务');
 await group.click();
 await page.getByRole('textbox',{name:'搜索用例业务',exact:true}).press('Escape');
 await expect(page.getByRole('listbox',{name:'用例业务列表'})).toHaveCount(0);
 await page.screenshot({path:path.join(root,'workspace/qa/group-picker.png'),fullPage:true});
 await page.getByLabel('搜索用例').fill('gemini');
 await expect(page.locator('tbody tr').first()).toContainText(/gemini/i);
 await page.getByRole('button',{name:'载入',exact:false}).first().click();
 await expect(page.getByRole('heading',{name:'请求工作台',exact:true})).toBeVisible();
 await expect(page.getByLabel('请求名称')).not.toHaveValue('新建请求');
 await page.reload();
 await expect(page.getByRole('heading',{name:'请求工作台',exact:true})).toBeVisible();
 await expect(page.getByLabel('本机配对码')).toHaveCount(0);
 await page.getByRole('button',{name:'用例库',exact:false}).click();
 await expect.poll(async()=>Number((await page.locator('.case-library .pagination').innerText()).match(/共 (\d+) 个接口/)?.[1]||0)).toBeGreaterThanOrEqual(146);
 await page.screenshot({path:path.join(root,'workspace/qa/apipost-cases.png'),fullPage:true});
});
