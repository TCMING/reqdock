test('链接资源确认来源后下载并预览，不直接访问第三方链接',async({page})=>{
 await page.goto('/');
 const code=execFileSync(path.join(root,'.venv/Scripts/python.exe'),['-m','api_post','pair','--port','18767','--workspace',process.env.API_LAB_E2E_WORKSPACE!],{cwd:root,encoding:'utf8',stdio:['ignore','pipe','ignore']}).trim();
 await page.getByLabel('本机配对码').fill(code);await page.getByRole('button',{name:'连接工作区'}).click();
 const session=await (await page.request.get('/api/auth/session')).json();
 const name='链接预览 '+Date.now();
 const response=await page.request.post('/api/resources',{headers:{Origin:'http://127.0.0.1:18767','X-CSRF-Token':session.csrf},data:{name,kind:'image',addresses:[{purpose:'third_party',url:'http://127.0.0.1:18768/preview-fixture.png',network_scope:'local',trusted:false}]}});
 expect(response.ok()).toBeTruthy();
 await page.getByRole('button',{name:'资源库',exact:false}).first().click();await page.getByLabel('搜索资源').fill(name);
 await page.locator('.resource-row').filter({hasText:name}).getByRole('button',{name:'预览',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'资源预览'});
 await expect(dialog.getByRole('button',{name:'下载并预览'})).toBeDisabled();
 await dialog.getByLabel('允许从此来源下载文件用于预览').check();
 await dialog.getByRole('button',{name:'下载并预览'}).click();
 await expect(dialog.getByRole('img')).toBeVisible();
 await expect.poll(()=>dialog.getByRole('img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBe(1);
 await expect(dialog.getByRole('img')).toHaveAttribute('src',/^\/api\/resources\//);
 await dialog.getByRole('button',{name:'关闭',exact:false}).click();
 await expect(page.locator('.resource-local-cell')).toContainText('objects');
});
